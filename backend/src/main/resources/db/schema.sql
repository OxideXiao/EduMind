-- SmartTeachingPlatform Database Schema (PostgreSQL)
-- Based on teaching_ops_pg.sql — 27 tables
-- All tables use IF NOT EXISTS for safe re-run

-- ============================================================
-- Level 0 — no foreign keys
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    real_name     varchar(100),
    email         varchar(150),
    phone         varchar(30),
    avatar_url    varchar(500),
    status        varchar(30)  NOT NULL DEFAULT 'active',
    created_at    timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email),
    CONSTRAINT users_chk_1 CHECK (status IN ('active','disabled'))
);
CREATE INDEX IF NOT EXISTS idx_users_email    ON users (email);
CREATE INDEX IF NOT EXISTS idx_users_username ON users (username);

CREATE TABLE IF NOT EXISTS roles (
    id        serial       PRIMARY KEY,
    role_code varchar(50)  NOT NULL,
    role_name varchar(100) NOT NULL,
    CONSTRAINT uk_roles_code UNIQUE (role_code)
);

-- ============================================================
-- Level 1 — depend on users / roles only
-- ============================================================

CREATE TABLE IF NOT EXISTS courses (
    id          bigserial    PRIMARY KEY,
    course_name varchar(200) NOT NULL,
    course_code varchar(100),
    semester    varchar(100),
    teacher_id  bigint       NOT NULL,
    description text,
    invite_code varchar(50),
    status      varchar(30)  NOT NULL DEFAULT 'draft',
    created_at  timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_courses_code   UNIQUE (course_code),
    CONSTRAINT uk_courses_invite UNIQUE (invite_code),
    CONSTRAINT courses_chk_1 CHECK (status IN ('draft','active','archived'))
);
CREATE INDEX IF NOT EXISTS idx_courses_teacher_id ON courses (teacher_id);
CREATE INDEX IF NOT EXISTS idx_courses_semester   ON courses (semester);

CREATE TABLE IF NOT EXISTS user_roles (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    role_id bigint NOT NULL,
    CONSTRAINT uk_user_roles_user_role UNIQUE (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS idx_user_roles_role ON user_roles (role_id);

-- ============================================================
-- Level 2 — depend on courses / users
