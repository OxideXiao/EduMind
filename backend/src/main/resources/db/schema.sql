CREATE TABLE IF NOT EXISTS knowledge_nodes (
    id          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   bigint        NOT NULL,
    parent_id   bigint,
    node_name   varchar(200)  NOT NULL,
    node_desc   text,
    difficulty  int           NOT NULL DEFAULT 1,
    sort_order  int           NOT NULL DEFAULT 0,
    x_position  decimal(10,2),
    y_position  decimal(10,2),
    status      varchar(30)   NOT NULL DEFAULT 'active',
    created_at  timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT knowledge_nodes_chk_1 CHECK (difficulty BETWEEN 1 AND 5),
    CONSTRAINT knowledge_nodes_chk_2 CHECK (status IN ('active','hidden'))
);
CREATE INDEX IF NOT EXISTS idx_knowledge_nodes_course_id ON knowledge_nodes (course_id);
CREATE INDEX IF NOT EXISTS idx_knowledge_nodes_parent_id ON knowledge_nodes (parent_id);

CREATE TABLE IF NOT EXISTS resources (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     bigint        NOT NULL,
    uploader_id   bigint        NOT NULL,
    resource_name varchar(200)  NOT NULL,
    resource_type varchar(30)   NOT NULL,
    file_url      varchar(1000) NOT NULL,
    file_size     bigint,
    duration      int,
    description   text,
    created_at    timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT resources_chk_1 CHECK (resource_type IN ('pdf','ppt','video','link','document','image','other')),
    CONSTRAINT resources_chk_2 CHECK ((file_size IS NULL) OR (file_size >= 0)),
    CONSTRAINT resources_chk_3 CHECK ((duration  IS NULL) OR (duration >= 0))
);
CREATE INDEX IF NOT EXISTS idx_resources_course_id   ON resources (course_id);
CREATE INDEX IF NOT EXISTS idx_resources_uploader_id ON resources (uploader_id);

CREATE TABLE IF NOT EXISTS quizzes (
    id          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   bigint        NOT NULL,
    title       varchar(200)  NOT NULL,
    description text,
    start_time  timestamp,
    end_time    timestamp,
    total_score decimal(8,2)  NOT NULL DEFAULT 0.00,
